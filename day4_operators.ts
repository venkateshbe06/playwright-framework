// Operators
// Arithmetic Operator
let a : number = 10, b : number = 20;
console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
console.log(a ** b);

// Assignment Operator
let x : number = 4, y : number = 5;
console.log(x += y);
console.log(x -= y);
console.log(x *= y);
console.log(x /= y);
console.log(x %= y);
console.log(x **=y);


// Relation operators - Output will be boolean type 

let a1 : number = 10, b1 : number = 20;
console.log(a1 > b1);
console.log(a1 < b1);
console.log(a1 >= b1);
console.log(a1 <= b1);
console.log(a1 == b1);
console.log(a1 != b1);
console.log(a1 === b1);

